#!/bin/bash
# Phase B, first slice (docs/PLAN-ENGINE-RESOLUTION.md): the real resolver's steps carried out on
# Godot's physics server through IArenaSpace.
# Usage: run-phase-b-space.sh <path-to-Godot_console.exe> <output-folder>
#
# Reads, one run at a time (the figures are wall clocks), on the arena's demo roster (3v3):
#   - the core resolver and the engine space, three runs each, 10,000 fights: throughput;
#   - the engine space twice with fingerprints, the frame lane, and the second half of the seeds
#     alone: determinism, lane identity and seed purity;
#   - every step tested against only the steps that can touch someone: the pre-check is lossless;
#   - 20,000 fights of each resolver: the first parity reading;
#   - the engine space timed by piece.
GODOT=$1
# Absolute: Godot's --path moves its working directory into the project, so a relative --digest would
# land there.
OUT=$(mkdir -p "$2" && cd "$2" && pwd)
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
DIG="$OUT/digests"
mkdir -p "$DIG"

# The editor binary loads the project's Debug assemblies; -p:Optimize=true makes them optimised ones.
dotnet build "$ROOT/src/Game/Domina.Game.csproj" -c Debug -p:Optimize=true > "$DIG/build.txt" 2>&1 \
  || { echo "build failed, see $DIG/build.txt"; exit 1; }

bed() {
  name=$1; shift
  "$GODOT" --headless "$@" > "$OUT/$name.txt" 2>&1
  grep -E '^RESULT' "$OUT/$name.txt" | sed "s/^RESULT/$name:/"
}

# Identical lines between two fingerprint files, out of the first file's count.
same() { paste -d' ' "$1" "$2" | awk '{ if ($1" "$2" "$3" "$4 == $5" "$6" "$7" "$8) s++ } END { print s+0 "/" NR }'; }

SCENE=(--path "$ROOT/src/Game" res://Bed/engine_bed.tscn --)
FRAME=(--fixed-fps 20 "${SCENE[@]}")

{
  for i in 1 2 3; do bed "core-$i" "${SCENE[@]}" --fighter core; done
  bed engine-1 "${SCENE[@]}" --fighter engine --digest "$DIG/engine-1.txt"
  bed engine-2 "${SCENE[@]}" --fighter engine --digest "$DIG/engine-2.txt"
  bed engine-3 "${SCENE[@]}" --fighter engine
  bed engine-frame-256 "${FRAME[@]}" --fighter engine --lane frame --slots 256 --digest "$DIG/engine-frame.txt"
  bed engine-second-half "${SCENE[@]}" --fighter engine --seed 5001 --fights 5000 --digest "$DIG/engine-half.txt"
  bed engine-every "${SCENE[@]}" --fighter engine --motion every --digest "$DIG/engine-every.txt"
  bed engine-profile "${SCENE[@]}" --fighter engine --profile
  bed parity-core-20k "${SCENE[@]}" --fighter core --fights 20000
  bed parity-engine-20k "${SCENE[@]}" --fighter engine --fights 20000

  tail -5000 "$DIG/engine-1.txt" > "$DIG/engine-1-second-half.txt"
  echo
  echo "identical fights, run 1 vs run 2:                 $(same "$DIG/engine-1.txt" "$DIG/engine-2.txt")"
  echo "identical fights, manual lane vs frame lane:      $(same "$DIG/engine-1.txt" "$DIG/engine-frame.txt")"
  echo "identical fights, seeds 5001.. alone vs in sweep: $(same "$DIG/engine-1-second-half.txt" "$DIG/engine-half.txt")"
  echo "identical fights, contact pre-check vs every:     $(same "$DIG/engine-1.txt" "$DIG/engine-every.txt")"
  echo
  echo "parity, 20,000 fights (core | engine):"
  for f in parity-core-20k parity-engine-20k; do
    grep -E '^(fights|outcomes|blows)' "$OUT/$f.txt" | sed "s/^/  $f: /"
  done
} | tee "$OUT/summary.txt"

# The fingerprint files are a few hundred kilobytes each and are regenerated by this script.
rm -r "$DIG"
