#!/bin/bash
# Phase A of docs/PLAN-ENGINE-RESOLUTION.md: the engine bed's gate.
# Usage: run-phase-a.sh <path-to-Godot_console.exe> <output-folder>
#
# Builds the Godot project optimised, then reads, one run at a time (the figures are wall clocks):
#   - the core resolver inside Godot, three times: the calibration;
#   - the gate configuration three times, two of them with every fight's fingerprint, compared;
#   - the frame lane against the manual lane, fingerprint by fingerprint;
#   - one variant per engine piece, to show what each costs;
#   - the kinematic body in both lanes, to show why the bodies are static.
GODOT=$1
# Absolute: Godot's --path moves its working directory into the project, so a relative --digest would
# land there.
OUT=$(mkdir -p "$2" && cd "$2" && pwd)
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
DIG="$OUT/digests"
mkdir -p "$DIG"

# The editor binary loads the project's Debug assemblies; -p:Optimize=true makes them optimised ones.
dotnet build "$ROOT/src/Game/Domina.Game.csproj" -c Debug -p:Optimize=true > "$DIG/build.txt" 2>&1 \
  || { echo "build failed, see $DIG/build.txt"; exit 1; }

bed() {
  name=$1; shift
  "$GODOT" --headless "$@" > "$OUT/$name.txt" 2>&1
  grep -E '^RESULT' "$OUT/$name.txt" | sed "s/^RESULT/$name:/"
}

# Identical lines between two fingerprint files, out of the first file's count.
same() { paste -d' ' "$1" "$2" | awk '{ if ($1" "$2" "$3" "$4 == $5" "$6" "$7" "$8) s++ } END { print s+0 "/" NR }'; }

SCENE=(--path "$ROOT/src/Game" res://Bed/engine_bed.tscn --)
FRAME=(--fixed-fps 20 "${SCENE[@]}")

{
  for i in 1 2 3; do bed "core-$i" "${SCENE[@]}" --fighter core; done
  bed gate-1 "${SCENE[@]}" --digest "$DIG/gate-1.txt"
  bed gate-2 "${SCENE[@]}" --digest "$DIG/gate-2.txt"
  bed gate-3 "${SCENE[@]}"
  bed frame-256 "${FRAME[@]}" --lane frame --slots 256 --digest "$DIG/frame-256.txt"
  bed gate-profile "${SCENE[@]}" --profile
  bed blade-query "${SCENE[@]}" --blade query --profile
  bed clip-mixer "${SCENE[@]}" --clip mixer --profile
  bed rebuild "${SCENE[@]}" --rebuild --profile
  bed character-manual "${SCENE[@]}" --body character --fights 1000 --digest "$DIG/character-manual.txt"
  bed character-frame "${FRAME[@]}" --lane frame --slots 64 --body character --fights 1000 \
    --digest "$DIG/character-frame.txt"

  head -1000 "$DIG/gate-1.txt" > "$DIG/gate-1-first-1000.txt"
  echo
  echo "identical fights, gate run 1 vs run 2:          $(same "$DIG/gate-1.txt" "$DIG/gate-2.txt")"
  echo "identical fights, manual lane vs frame lane:    $(same "$DIG/gate-1.txt" "$DIG/frame-256.txt")"
  echo "identical fights, kinematic manual vs frame:    $(same "$DIG/character-manual.txt" "$DIG/character-frame.txt")"
  echo "identical fights, static vs kinematic (manual): $(same "$DIG/gate-1-first-1000.txt" "$DIG/character-manual.txt")"
} | tee "$OUT/summary.txt"

# The fingerprint files are a few hundred kilobytes each and are regenerated by this script.
rm -r "$DIG"
